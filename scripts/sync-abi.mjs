// Copies the registry's ABI from the Foundry build into the grants package. Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const artifact = JSON.parse(readFileSync(new URL("contracts/out/GrantRegistry.sol/GrantRegistry.json", root), "utf8"));
const source = `// Generated by scripts/sync-abi.mjs from contracts/src/GrantRegistry.sol. Do not edit.
export const grantRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(new URL("packages/grants/src/abi.ts", root), source);
console.log(`Wrote ${artifact.abi.length} ABI entries to packages/grants/src/abi.ts`);
